"""Generate docs/CODEMAP.md: every module, class and function with its one-line purpose.

    python scripts/gen_codemap.py

Run it after structural changes. The map is the cheapest way to give a coding agent (or
yourself) the project layout: paste it into a chat, or reference it with @docs/CODEMAP.md.
"""

from __future__ import annotations

import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "CODEMAP.md"
PY_ROOTS = [ROOT / "backend" / "app", ROOT / "backend" / "eval"]
TS_ROOT = ROOT / "frontend" / "src"


def first_line(doc: str | None) -> str:
    return doc.strip().splitlines()[0].strip() if doc and doc.strip() else ""


def signature(fn: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    args = ast.unparse(fn.args)
    ret = f" -> {ast.unparse(fn.returns)}" if fn.returns else ""
    prefix = "async " if isinstance(fn, ast.AsyncFunctionDef) else ""
    return f"{prefix}{fn.name}({args}){ret}"


def describe_py(path: Path) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    rel = path.relative_to(ROOT)
    lines = [f"### `{rel}`", ""]
    summary = first_line(ast.get_docstring(tree))
    if summary:
        lines += [summary, ""]
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            bases = f"({', '.join(ast.unparse(b) for b in node.bases)})" if node.bases else ""
            doc = first_line(ast.get_docstring(node))
            lines.append(f"- **class `{node.name}{bases}`** {('- ' + doc) if doc else ''}".rstrip())
            for item in node.body:
                if isinstance(item, ast.FunctionDef | ast.AsyncFunctionDef) and not item.name.startswith("_"):
                    d = first_line(ast.get_docstring(item))
                    lines.append(f"  - `{signature(item)}`" + (f" - {d}" if d else ""))
        elif isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef) and not node.name.startswith("_"):
            d = first_line(ast.get_docstring(node))
            lines.append(f"- `{signature(node)}`" + (f" - {d}" if d else ""))
    lines.append("")
    return lines


def describe_ts(path: Path) -> list[str]:
    text = path.read_text(encoding="utf-8")
    rel = path.relative_to(ROOT)
    names = re.findall(r"export (?:default )?(?:async )?(?:function|const|type) (\w+)", text)
    return [f"- `{rel}`: " + (", ".join(f"`{n}`" for n in names) if names else "(no exports)")]


def main() -> None:
    out = [
        "# Code map",
        "",
        "_Generated by `python scripts/gen_codemap.py`. Do not edit by hand._",
        "",
        "## Backend (Python)",
        "",
    ]
    for root in PY_ROOTS:
        for path in sorted(root.rglob("*.py")):
            if path.name == "__init__.py":
                continue
            out += describe_py(path)
    out += ["## Frontend (TypeScript)", ""]
    for path in sorted(TS_ROOT.rglob("*.ts*")):
        out += describe_ts(path)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(out)} lines)")


if __name__ == "__main__":
    main()
